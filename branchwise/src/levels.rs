//! The lessons: what each teaches, the repository it starts from (setup
//! commands), and one way to reach its goal (the goal is the state that
//! solution leaves). Text in `backticks` is drawn as code.
//!
//! Setup commands are real commands, plus `#c file message`, a commit that
//! adds the message (or what follows a `|`) as a line of file, `#clone`,
//! which puts the repository on origin, and `@origin cmd`, a teammate's
//! work pushed to origin.

pub struct Level {
    pub chapter: &'static str,
    pub title: &'static str,
    pub text: &'static str,
    pub goal: &'static str,
    pub hint: &'static str,
    /// files in ~/app before the setup runs
    pub files: &'static [&'static str],
    pub setup: &'static [&'static str],
    pub solution: &'static [&'static str],
    /// buttons that type for you, for touch screens
    pub chips: &'static [&'static str],
}


