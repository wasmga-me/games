#!/usr/bin/env python3
"""Packs rendered sprites into one sheet for a Rust game on the wg engine.

    python3 pack.py JOBS.json RENDERED_DIR OUT.png OUT.rs [--colours N]

Each job's PNG (from render.mjs) is cropped to what it draws and packed into
OUT.png. OUT.rs gets the sheet's bytes, an `Art` per sprite (its box in the
sheet, where the model's origin lands in it, and pixels per model unit) and
a constant per sprite named after the job. --colours N stores the sheet with
a palette of N colours (smaller; check the art still looks right).
Needs Pillow.
"""
import json
import math
import os
import sys

from PIL import Image

GAP = 1
WIDTH = 1024


def project(v, job):
    """A model-space offset as pixels across and down the render."""
    yaw, pitch = math.radians(job.get("yaw", 0)), math.radians(job["pitch"])
    right = (math.cos(yaw), 0, -math.sin(yaw))
    up = (-math.sin(yaw) * math.sin(pitch), math.cos(pitch), -math.cos(yaw) * math.sin(pitch))
    dot = lambda a, b: sum(x * y for x, y in zip(a, b))
    return dot(v, right) * job["ppu"], -dot(v, up) * job["ppu"]


def main(argv):
    colours = None
    if "--colours" in argv:
        i = argv.index("--colours")
        colours = int(argv[i + 1])
        del argv[i : i + 2]
    jobs_file, rendered, out_png, out_rs = argv
    jobs = json.load(open(jobs_file))
    parts = []
    for job in jobs:
        im = Image.open(os.path.join(rendered, job["name"] + ".png")).convert("RGBA")
        box = im.getchannel("A").point(lambda a: 255 if a > 2 else 0).getbbox()
        if box is None:
            sys.exit(f"{job['name']} draws nothing")
        crop = im.crop(box)
        # the render's middle is the job's centre (the origin by default);
        # find where the origin lands from there
        ox, oy = project([-c for c in job.get("center", [0, 0, 0])], job)
        ax = im.width / 2 + ox - box[0]
        ay = im.height / 2 + oy - box[1]
        parts.append((job, crop, ax, ay))
    # tallest first, along shelves
    order = sorted(range(len(parts)), key=lambda i: -parts[i][1].height)
    x = y = shelf = 0
    place = {}
    for i in order:
        crop = parts[i][1]
        if x + crop.width > WIDTH:
            x, y, shelf = 0, y + shelf + GAP, 0
        place[i] = (x, y)
        x += crop.width + GAP
        shelf = max(shelf, crop.height)
    sheet = Image.new("RGBA", (WIDTH, y + shelf), (0, 0, 0, 0))
    for i, (job, crop, ax, ay) in enumerate(parts):
        sheet.paste(crop, place[i])
    if colours:
        sheet = sheet.quantize(colours, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    sheet.save(out_png, optimize=True)
    lines = [
        f"// Generated by games-src/tools/render3d/pack.py from {os.path.basename(jobs_file)}, do not edit.",
        "#![allow(dead_code)]",
        "",
        "/// One sprite: its box in the sheet, where the model's origin (on the",
        "/// ground, under its middle) lands, from the box's top left, and the",
        "/// sheet's pixels per model unit.",
        "pub struct Art {",
        "    pub x: i32,",
        "    pub y: i32,",
        "    pub w: i32,",
        "    pub h: i32,",
        "    pub ax: f32,",
        "    pub ay: f32,",
        "    pub ppu: f32,",
        "}",
        "",
        f'pub static SHEET: &[u8] = include_bytes!("{os.path.basename(out_png)}");',
        "",
        f"pub static ARTS: [Art; {len(parts)}] = [",
    ]
    for i, (job, crop, ax, ay) in enumerate(parts):
        px, py = place[i]
        lines.append(
            f"    Art {{ x: {px}, y: {py}, w: {crop.width}, h: {crop.height}, ax: {ax:.1f}, ay: {ay:.1f}, ppu: {float(job['ppu']):.1f} }},"
        )
    lines.append("];")
    lines.append("")
    for i, (job, *_) in enumerate(parts):
        lines.append(f"pub const {job['name'].upper().replace('-', '_')}: usize = {i};")
    open(out_rs, "w").write("\n".join(lines) + "\n")
    print(f"{out_png}: {sheet.width}x{sheet.height}, {os.path.getsize(out_png)} bytes, {len(parts)} sprites")


if __name__ == "__main__":
    main(sys.argv[1:])
